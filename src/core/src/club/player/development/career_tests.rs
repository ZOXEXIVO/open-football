/// Twins doing the same week of sessions for forty weeks, rested to the same
/// condition before each week.
struct TrainingTwins;

impl TrainingTwins {
    fn season(player: &mut Player, coach: &Staff, sessions: &[TrainingType]) {
        let start = Cohort::start() + Duration::days(60);
        for week in 0..40 {
            let date = start + Duration::days(week * 7);
            player.player_attributes.condition = 9500;
            player.player_attributes.jadedness = 0;
            for session_type in sessions {
                let session = TrainingSession {
                    session_type: session_type.clone(),
                    intensity: TrainingIntensity::Moderate,
                    duration_minutes: 75,
                    focus_positions: vec![],
                    participants: vec![],
                };
                let at = date.and_hms_opt(10, 0, 0).unwrap();
                PlayerTraining::train(player, coach, &session, at, Club::AVERAGE.facilities)
                    .apply_to_player(player, date);
            }
        }
    }
}

#[test]
fn what_the_squad_trains_matters() {
    let coach = Club::AVERAGE.coach();
    let mut with = Scenario::player(3101, PlayerPositionType::DefenderCenter, 20, 150, 0.5);
    with.draw_blueprint(Cohort::start());
    let mut without = with.clone();
    TrainingTwins::season(
        &mut with,
        &coach,
        &[TrainingType::Defending, TrainingType::Passing],
    );
    TrainingTwins::season(
        &mut without,
        &coach,
        &[TrainingType::Shooting, TrainingType::Passing],
    );
    let (a, b) = (skills_to_array(&with), skills_to_array(&without));
    for key in [SkillKey::Tackling, SkillKey::Marking] {
        assert!(
            a[key.idx()] > b[key.idx()],
            "{key:?}: {:.3} with the unit's defending, {:.3} without",
            a[key.idx()],
            b[key.idx()]
        );
    }
}

#[test]
fn better_coaching_more_growth() {
    let sessions = [
        TrainingType::Passing,
        TrainingType::Positioning,
        TrainingType::BallControl,
        TrainingType::Strength,
    ];
    let mut boy = Scenario::player(3201, PlayerPositionType::MidfielderCenter, 19, 150, 0.45);
    boy.draw_blueprint(Cohort::start());
    let before: f32 = skills_to_array(&boy).iter().sum();
    let grown = |coaching: u8| {
        let mut player = boy.clone();
        let coach = Club {
            coaching,
            ..Club::AVERAGE
        }
        .coach();
        TrainingTwins::season(&mut player, &coach, &sessions);
        skills_to_array(&player).iter().sum::<f32>() - before
    };
    let (good, poor) = (grown(17), grown(6));
    assert!(
        good > poor,
        "a coach of 17 gave {good:.2} attribute points, a coach of 6 {poor:.2}"
    );
}

#[test]
fn a_regulars_growth_has_named_sources() {
    let career = Scenario::regular(
        Scenario::player(3301, PlayerPositionType::MidfielderCenter, 18, 150, 0.5),
        24,
    );
    let mut by_source = [0.0f32; GrowthSource::COUNT];
    for mark in career.marks.iter().filter(|m| m.age > 18 && m.age <= 24) {
        for (source, families) in mark.growth.iter().enumerate() {
            by_source[source] += families.iter().sum::<f32>();
        }
    }
    let total: f32 = by_source.iter().sum();
    let sessions = by_source[GrowthSource::Sessions as usize];
    let matches = by_source[GrowthSource::Matches as usize];
    assert!(total > 0.0, "a regular from 18 to 24 grew {total:.2}");
    assert!(
        sessions + matches >= 0.75 * total,
        "sessions {sessions:.1} and matches {matches:.1} of {total:.1}"
    );
    assert!(
        sessions >= 0.25 * total && matches >= 0.25 * total,
        "sessions {sessions:.1} and matches {matches:.1} of {total:.1}"
    );
}
