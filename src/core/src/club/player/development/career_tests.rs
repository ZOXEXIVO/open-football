// ── The development spec's scenarios ───────────────────────────────────
//
// Each is ignored until the stage of `player-development-system` that makes
// it true; the reason names the stage.

/// Single careers for the scenarios: a player built at `age` holding `share`
/// of his potential, with every other input at the grid's defaults.
struct Scenario;

impl Scenario {
    fn player(id: u32, position: PlayerPositionType, age: u32, pa: u8, share: f32) -> Player {
        let ca = (pa as f32 * share).round() as u8;
        Prospect::build(id, position, Cohort::start(), age, pa, ca, 12.0)
    }

    /// The player's CA re-read after a test has shaped his profile.
    fn refit(mut player: Player) -> Player {
        player.player_attributes.current_ability = player
            .skills
            .calculate_ability_for_position(player.position())
            .min(player.player_attributes.potential_ability);
        player
    }

    /// The database's median natural fitness (12) and professionalism (13).
    fn median(mut player: Player) -> Player {
        player.skills.physical.natural_fitness = 12.0;
        player.attributes.professionalism = 13.0;
        Self::refit(player)
    }

    fn run(player: Player, spells: Vec<Spell>, to_age: i32) -> Career {
        Career::with_spells(player, spells, Cohort::start()).run_to_age(to_age)
    }

    fn regular(player: Player, to_age: i32) -> Career {
        Self::run(
            player,
            GrowthTable::one(Club::AVERAGE, Role::Starter),
            to_age,
        )
    }

    fn at(career: &Career, age: u8) -> f32 {
        career.mark_at(age).ratio()
    }

    fn skill(career: &Career, age: u8, key: SkillKey) -> f32 {
        career.mark_at(age).skills[key.idx()]
    }
}

/// No birthday changes the pace of development. A season's training plans
/// change with its phases, so the weeks either side of a January birthday
/// differ by the calendar alone: each player is read against a twin born half
/// a year earlier over the same weeks, for whom those weeks hold no birthday.
#[test]
fn the_sixteenth_birthday() {
    let weekly = |position: PlayerPositionType, older: bool| -> Vec<(NaiveDate, f32)> {
        let mut player = Scenario::player(1500 + position as u32, position, 14, 150, 0.45);
        if older {
            let born = player.birth_date;
            player.birth_date = NaiveDate::from_ymd_opt(born.year() - 1, 7, 15).unwrap();
        }
        let career = Career::with_spells(
            player,
            GrowthTable::one(Club::AVERAGE, Role::YouthRegular),
            Cohort::start(),
        )
        .run_until(NaiveDate::from_ymd_opt(2032, 7, 2).unwrap());
        let mondays: Vec<NaiveDate> = (0..)
            .map(|w| NaiveDate::from_ymd_opt(2026, 7, 6).unwrap() + Duration::weeks(w))
            .take(career.weekly.len())
            .collect();
        career
            .weekly
            .windows(2)
            .zip(mondays.iter().skip(1))
            .map(|(w, day)| (*day, w[1].2 - w[0].2))
            .collect()
    };
    let mean = |weeks: &[(NaiveDate, f32)], from: NaiveDate, to: NaiveDate| {
        let v: Vec<f32> = weeks
            .iter()
            .filter(|(day, _)| *day >= from && *day < to)
            .map(|(_, d)| *d)
            .collect();
        v.iter().sum::<f32>() / v.len() as f32
    };
    let mut steps = Vec::new();
    for (_, position) in GrowthTable::CORE {
        let (player, twin) = (weekly(position, false), weekly(position, true));
        for birthday in 15..=19 {
            let day = NaiveDate::from_ymd_opt(2026 - 14 + birthday, 1, 15).unwrap();
            let (from, to) = (day - Duration::weeks(13), day + Duration::weeks(13));
            let step = (mean(&player, day, to) / mean(&player, from, day))
                / (mean(&twin, day, to) / mean(&twin, from, day));
            println!(
                "{position:?} at {birthday}: after / before {step:.3} of the twin's ({:+.3} -> {:+.3}; twin {:+.3} -> {:+.3})",
                mean(&player, from, day),
                mean(&player, day, to),
                mean(&twin, from, day),
                mean(&twin, day, to)
            );
            if (step - 1.0).abs() > 0.15 {
                steps.push(format!(
                    "{position:?} at {birthday}: growth after the birthday is {step:.3} of the twin's"
                ));
            }
        }
    }
    assert!(
        steps.is_empty(),
        "{}",
        steps.join(
            "
"
        )
    );
}

#[test]
fn an_early_and_a_late_developer() {
    for (_, position) in GrowthTable::CORE {
        let career = |years: f32| {
            let mut player = Scenario::player(3000 + position as u32, position, 17, 150, 0.47);
            player.development.timing = MaturationTiming::new(years);
            Scenario::regular(player, 27)
        };
        let (early, late) = (career(1.0), career(-1.0));
        println!(
            "{position:?}: early {:?} late {:?}",
            (17..=27u8)
                .map(|a| Scenario::at(&early, a))
                .collect::<Vec<_>>(),
            (17..=27u8)
                .map(|a| Scenario::at(&late, a))
                .collect::<Vec<_>>()
        );
        let at19 = Scenario::at(&early, 19) - Scenario::at(&late, 19);
        let at27 = Scenario::at(&early, 27) - Scenario::at(&late, 27);
        assert!(
            at19 >= 0.04,
            "{position:?} at 19: the early developer leads the late one by {at19:.3}"
        );
        assert!(
            at27.abs() <= 0.02,
            "{position:?} at 27: the early and the late developer are {at27:.3} apart"
        );
    }
}

