/// A European season: Saturday league fixtures from mid-August to late
/// May, friendlies on July Saturdays.
struct Calendar;

impl Calendar {
    /// `Some(is_friendly)` on match days.
    fn fixture(date: NaiveDate) -> Option<bool> {
        if date.weekday() != Weekday::Sat {
            return None;
        }
        let (m, d) = (date.month(), date.day());
        let in_season = (m == 8 && d >= 16) || m >= 9 || m <= 4 || (m == 5 && d <= 25);
        if in_season {
            Some(false)
        } else if m == 7 && d >= 10 {
            Some(true)
        } else {
            None
        }
    }

    fn is_official(date: NaiveDate) -> bool {
        Self::fixture(date) == Some(false)
    }

    fn is_off_season(date: NaiveDate) -> bool {
        let (m, d) = (date.month(), date.day());
        (m == 5 && d > 25) || m == 6 || m == 7 || (m == 8 && d < 16)
    }

    /// The fixture window the country pipeline writes before the clubs
    /// train: the league has played, so today's match is already recent.
    /// The youth side is taken to train around the same Saturdays.
    fn window(today: NaiveDate) -> TeamFixtureWindow {
        let dates = |days: &mut dyn Iterator<Item = i64>| -> Vec<NaiveDate> {
            days.map(|off| today + Duration::days(off))
                .filter(|d| Self::is_official(*d))
                .take(4)
                .collect()
        };
        TeamFixtureWindow {
            refreshed: Some(today),
            upcoming: dates(&mut (1..=35)),
            recent: dates(&mut (0..=35).map(|back| -back)),
        }
    }

    /// `TeamTraining::determine_phase`.
    fn phase(date: NaiveDate) -> PeriodizationPhase {
        match date.month() {
            6 | 7 => PeriodizationPhase::PreSeason,
            8 | 9 => PeriodizationPhase::EarlySeason,
            3 | 4 => PeriodizationPhase::LateSeason,
            5 => PeriodizationPhase::OffSeason,
            _ => PeriodizationPhase::MidSeason,
        }
    }
}

/// Generator-shaped starting profiles: the generation weights give the
/// role's shape, `SkillMaturation` the age's share of each attribute, and
/// the whole profile is then fitted to the requested CA.
struct Prospect;

impl Prospect {
    fn skills(
        position: PlayerPositionType,
        age: u32,
        pa: u8,
        ca: u8,
        character: f32,
        stream: &mut Stream,
    ) -> PlayerSkills {
        let level = PlayerSkills::ability_skill_level(pa);
        let spread = (level * 0.5).max(2.5);
        let shape = PositionWeights::for_position(position);
        let mut arr = [0.0f32; SKILL_COUNT];
        for (i, value) in arr.iter_mut().enumerate().take(SK_MATCH_READINESS) {
            let maturity = SkillMaturation::ratio(
                age as f32 + 0.5,
                PositionalSkillCeilings::maturation_group(i),
            );
            let mean = level * maturity + (shape[i] - 1.0) * spread;
            *value = (mean + stream.normal() * 1.2).clamp(1.0, 20.0);
        }
        arr[SK_MATCH_READINESS] = 14.0;
        if position == PlayerPositionType::Goalkeeper {
            let maturity = SkillMaturation::ratio(age as f32 + 0.5, MaturationGroup::Goalkeeping);
            for value in &mut arr[SK_GK_AERIAL_REACH..=SK_GK_THROWING] {
                *value = (level * maturity + stream.normal() * 1.2).clamp(1.0, 20.0);
            }
        }
        let mut skills = PlayerSkills::default();
        write_array_into(&mut skills, &arr);
        skills.mental.determination = character;
        skills.mental.work_rate = character;
        skills.fit_to_ability(position, ca, 20.0, None);
        skills
    }

    /// A player of `age` on `start`. `character` is his professionalism,
    /// ambition, determination and work rate alike.
    fn build(
        id: u32,
        position: PlayerPositionType,
        start: NaiveDate,
        age: u32,
        pa: u8,
        ca: u8,
        character: f32,
    ) -> Player {
        let mut stream = Stream(0x5EED ^ (id as u64) << 20 ^ (pa as u64) << 8 ^ age as u64);
        let skills = Self::skills(position, age, pa, ca, character, &mut stream);
        let birth = NaiveDate::from_ymd_opt(start.year() - age as i32, 1, 15).unwrap();
        let attributes = PlayerAttributes {
            potential_ability: pa,
            current_ability: skills.calculate_ability_for_position(position),
            condition: 9500,
            fitness: 8500,
            injury_proneness: 8,
            ..Default::default()
        };
        PlayerBuilder::new()
            .id(id)
            .full_name(FullName::new("Career".to_string(), format!("{id}")))
            .birth_date(birth)
            .country_id(1)
            .attributes(PersonAttributes {
                professionalism: character,
                ambition: character,
                ..PersonAttributes::default()
            })
            .skills(skills)
            .positions(PlayerPositions {
                positions: vec![PlayerPosition {
                    position,
                    level: 20,
                }],
            })
            .player_attributes(attributes)
            .build()
            .unwrap()
    }
}

/// CA/PA of a profile sitting exactly on every ceiling the player may
/// reach at `age` — the most development allows him to hold.
struct Envelope;

impl Envelope {
    /// Every family's football banked at `share`.
    fn bank(player: &mut Player, share: f32) {
        for family in MaturationGroup::ALL {
            player.development.football.set(family, share);
        }
    }

    fn at(player: &Player, age: f32) -> f32 {
        let ceilings = PositionalSkillCeilings::for_player(player, age);
        let mut arr = skills_to_array(player);
        for (i, v) in arr.iter_mut().enumerate() {
            if i != SK_MATCH_READINESS && *v > 0.0 {
                *v = ceilings.at(i);
            }
        }
        let mut skills = player.skills;
        write_array_into(&mut skills, &arr);
        skills.calculate_ability_for_position(player.position()) as f32
            / player.player_attributes.potential_ability as f32
    }
}

/// Maturation families in the order the grid prints them.
const FAMILIES: [&str; MaturationGroup::COUNT] = ["tec", "men", "phy", "exp", "gk"];

/// A player's state at the close of a season (1 July), and how the season
/// that ended built it.
#[derive(Clone, Copy, Debug)]
struct SeasonMark {
    age: u8,
    ca: u8,
    skill_ca: u8,
    pa: u8,
    lowest: f32,
    highest: f32,
    /// CA/PA of a profile sitting on every ceiling.
    envelope: f32,
    exposure: f32,
    /// Mean of each family's attributes the position trains.
    family_mean: [f32; MaturationGroup::COUNT],
    /// Mean of attribute / ceiling over each family's key attributes.
    family_key_fill: [f32; MaturationGroup::COUNT],
    /// The season's attribute change by source and family, from his ledger.
    growth: [[f32; MaturationGroup::COUNT]; GrowthSource::COUNT],
    skills: [f32; SKILL_COUNT],
}

impl SeasonMark {
    fn ratio(&self) -> f32 {
        self.ca as f32 / self.pa as f32
    }
}

struct Career {
    player: Player,
    club: Club,
    role: Role,
    spells: Vec<Spell>,
    spell: usize,
    coach: Staff,
    date: NaiveDate,
    fixtures: u32,
    marks: Vec<SeasonMark>,
    sessions: BTreeMap<String, u32>,
    /// `(age, CA, skill-derived CA)` at every weekly tick.
    weekly: Vec<(f32, u8, f32)>,
}

impl Career {
    const RATING: f32 = 6.9;

    fn new(player: Player, club: Club, role: Role, start: NaiveDate) -> Self {
        Self::with_spells(
            player,
            vec![Spell {
                from_age: 0,
                club,
                role,
            }],
            start,
        )
    }

    /// A career that moves from spell to spell on the 1 July after each
    /// spell's age is reached.
    fn with_spells(mut player: Player, spells: Vec<Spell>, start: NaiveDate) -> Self {
        if !player.development.blueprint.is_drawn() {
            player.draw_blueprint(start);
        }
        let first = spells[0];
        Career {
            player,
            club: first.club,
            role: first.role,
            spells,
            spell: 0,
            coach: first.club.coach(),
            date: start,
            fixtures: 0,
            marks: Vec::new(),
            sessions: BTreeMap::new(),
            weekly: Vec::new(),
        }
    }

    fn run_seasons(self, seasons: i32) -> Self {
        let end = NaiveDate::from_ymd_opt(self.date.year() + seasons, 7, 2).unwrap();
        self.run_until(end)
    }

    /// Through the summer the player turns `age`.
    fn run_to_age(self, age: i32) -> Self {
        let end = NaiveDate::from_ymd_opt(self.player.birth_date.year() + age, 7, 2).unwrap();
        self.run_until(end)
    }

    fn run_until(mut self, end: NaiveDate) -> Self {
        while self.date < end {
            self.day();
            self.date = self.date.succ_opt().unwrap();
        }
        self
    }

    fn mark_at(&self, age: u8) -> SeasonMark {
        *self
            .marks
            .iter()
            .find(|m| m.age == age)
            .expect("career did not reach that age")
    }

    fn peak(&self) -> SeasonMark {
        *self.marks.iter().max_by_key(|m| m.ca).unwrap()
    }

    /// The spell his age has reached. A spell that keeps the same club and
    /// football leaves the season running as it was.
    fn enter_spell(&mut self, today: NaiveDate) {
        let age = DateUtils::age(self.player.birth_date, today) as u32;
        let index = self
            .spells
            .iter()
            .rposition(|s| age >= s.from_age)
            .unwrap_or(0);
        if index == self.spell {
            return;
        }
        self.spell = index;
        let spell = self.spells[index];
        if spell.club.league_reputation != self.club.league_reputation || spell.role != self.role {
            self.club = spell.club;
            self.role = spell.role;
            self.coach = spell.club.coach();
        }
    }

    /// One simulated day, in the order the world runs it: the player's
    /// daily processing and the weekly tick, the club's sessions, the
    /// match result's exertion, then the country's off-season camp.
    fn day(&mut self) {
        let today = self.date;
        if today.month() == 7 && today.day() == 1 {
            self.close_season();
            self.enter_spell(today);
        }
        let injured = self.role == Role::Injured;
        if injured {
            self.player.player_attributes.is_injured = true;
        }
        let works = !matches!(self.role, Role::Injured | Role::Free);

        let form = self.player.training.form_recovery_baseline();
        self.player.load.daily_decay_with_form_target(today, form);
        self.player.process_condition_recovery(today);
        self.player.process_match_readiness_decay(today);
        if today.weekday() == Weekday::Mon {
            self.player.process_development(today);
            self.weekly.push((
                DateUtils::age_in_years(self.player.birth_date, today),
                self.player.player_attributes.current_ability,
                self.player
                    .skills
                    .ability_score_for_position(self.player.position()),
            ));
        }

        if works {
            self.train(today);
        }

        let appearance = match Calendar::fixture(today) {
            Some(true) if works && self.role != Role::Unused => Some((45.0, true)),
            Some(false) => {
                self.fixtures += 1;
                self.role.appearance(self.fixtures)
            }
            _ => None,
        };
        if let Some((minutes, friendly)) = appearance {
            self.player
                .on_match_exertion_minutes_only(minutes, today, friendly);
            let standard = match (friendly, self.role) {
                (true, Role::YouthRegular) if Calendar::is_official(today) => {
                    self.club.youth_standard
                }
                (true, _) => self.club.standard - Club::FRIENDLY_DROP,
                (false, _) => self.club.standard,
            };
            let mut official = self.player.statistics.clone();
            official.merge_from(&self.player.cup_statistics);
            let football = MatchFootball {
                minutes,
                standard,
                slot: self.player.position(),
                season_rating: official
                    .average_rating_realistic(self.player.position().position_group()),
                season_games: official.total_games(),
            };
            self.player.bank_football(&football, today);
            self.record_appearance(minutes, friendly);
            self.heal();
        }

        if Calendar::is_off_season(today) && works {
            self.player.on_offseason_camp_day(self.club.facilities);
        }
    }

    fn train(&mut self, today: NaiveDate) {
        let philosophy = CoachingPhilosophy {
            tactical_focus: TacticalFocus::Balanced,
            training_intensity: TrainingIntensityPreference::Medium,
            youth_focus: false,
            rotation_preference: RotationPreference::Moderate,
        };
        let window = Calendar::window(today);
        let plan = WeeklyTrainingPlan::generate_for_date(
            today,
            window.previous_before(today),
            window.next_after(today),
            window.fixtures_this_week(today),
            Calendar::phase(today),
            &philosophy,
        );
        let Some(sessions) = plan.sessions.get(&today.weekday()) else {
            return;
        };
        let at = today.and_hms_opt(0, 0, 0).unwrap();
        for session in sessions {
            if !Self::participates(&self.player, session) {
                continue;
            }
            *self
                .sessions
                .entry(format!("{:?}", session.session_type))
                .or_default() += 1;
            PlayerTraining::train(&self.player, &self.coach, session, at, self.club.facilities)
                .apply_to_player(&mut self.player, today);
            self.heal();
        }
    }

    /// `TeamTraining::select_participants` for a fit squad member.
    fn participates(player: &Player, session: &TrainingSession) -> bool {
        if player.player_attributes.condition_percentage() <= 30 {
            return false;
        }
        if player.player_attributes.is_in_recovery()
            && !matches!(
                session.session_type,
                TrainingType::Recovery
                    | TrainingType::LightRecovery
                    | TrainingType::Rehabilitation
                    | TrainingType::RestDay
                    | TrainingType::VideoAnalysis
                    | TrainingType::Positioning
            )
        {
            return false;
        }
        session.focus_positions.is_empty()
            || session
                .focus_positions
                .iter()
                .any(|p| player.positions.has_position(*p))
    }

    /// Careers measure development, not medical luck: the match and
    /// training injury rolls use the thread RNG, so an injury heals on
    /// the spot.
    fn heal(&mut self) {
        let a = &mut self.player.player_attributes;
        a.is_injured = false;
        a.injury_days_remaining = 0;
        a.recovery_days_remaining = 0;
        a.injury_type = None;
    }

    fn record_appearance(&mut self, minutes: f32, friendly: bool) {
        let stats = if friendly {
            &mut self.player.friendly_statistics
        } else {
            &mut self.player.statistics
        };
        if minutes >= 45.0 {
            stats.played += 1;
        } else {
            stats.played_subs += 1;
        }
        let weight = (minutes / 90.0).clamp(0.2, 1.0);
        stats.rating_points += Self::RATING * weight;
        stats.rating_weight += weight;
        stats.average_rating = stats.rating_points / stats.rating_weight;
        stats.rating_sum += Self::RATING;
        stats.rating_matches += 1;
    }

    fn close_season(&mut self) {
        let skills = skills_to_array(&self.player);
        let attributes = skills
            .iter()
            .enumerate()
            .filter(|(i, v)| *i != SK_MATCH_READINESS && **v > 0.0)
            .map(|(_, v)| *v);
        let age = DateUtils::age_in_years(self.player.birth_date, self.date);
        let weights = self.player.development.weights(&self.player);
        let ceilings = PositionalSkillCeilings::for_player(&self.player, age);
        let mut mark = SeasonMark {
            age: DateUtils::age(self.player.birth_date, self.date),
            ca: self.player.player_attributes.current_ability,
            skill_ca: self
                .player
                .skills
                .calculate_ability_for_position(self.player.position()),
            pa: self.player.player_attributes.potential_ability,
            lowest: attributes.clone().fold(f32::MAX, f32::min),
            highest: attributes.fold(f32::MIN, f32::max),
            envelope: Envelope::at(&self.player, age),
            exposure: self.player.development.football.share(),
            family_mean: [0.0; MaturationGroup::COUNT],
            family_key_fill: [0.0; MaturationGroup::COUNT],
            growth: [[0.0; MaturationGroup::COUNT]; GrowthSource::COUNT],
            skills,
        };
        let mut n = [0.0f32; MaturationGroup::COUNT];
        let mut nk = [0.0f32; MaturationGroup::COUNT];
        for i in 0..SKILL_COUNT {
            if i == SK_MATCH_READINESS || weights[i] <= 0.0 {
                continue;
            }
            let f = PositionalSkillCeilings::maturation_group(i) as usize;
            mark.family_mean[f] += skills[i];
            n[f] += 1.0;
            if weights[i] >= 1.0 {
                mark.family_key_fill[f] += (skills[i] / ceilings.at(i)).min(1.5);
                nk[f] += 1.0;
            }
        }
        for f in 0..MaturationGroup::COUNT {
            if n[f] > 0.0 {
                mark.family_mean[f] /= n[f];
            }
            if nk[f] > 0.0 {
                mark.family_key_fill[f] /= nk[f];
            }
        }
        let season = self.player.development.ledger.this_season();
        for source in GrowthSource::ALL {
            for family in MaturationGroup::ALL {
                mark.growth[source as usize][family as usize] = season.change(source, family);
            }
        }
        self.marks.push(mark);
        self.player.statistics = PlayerStatistics::default();
        self.player.cup_statistics = PlayerStatistics::default();
        self.player.friendly_statistics = PlayerStatistics::default();
    }
}

const OUTFIELD: [PlayerPositionType; 7] = [
    PlayerPositionType::DefenderCenter,
    PlayerPositionType::DefenderLeft,
    PlayerPositionType::DefensiveMidfielder,
    PlayerPositionType::MidfielderCenter,
    PlayerPositionType::AttackingMidfielderRight,
    PlayerPositionType::AttackingMidfielderCenter,
    PlayerPositionType::Striker,
];

/// One career per role, all under the same conditions.
struct Cohort {
    careers: Vec<Career>,
}

impl Cohort {
    fn start() -> NaiveDate {
        NaiveDate::from_ymd_opt(2026, 7, 1).unwrap()
    }

    fn every_role() -> Vec<PlayerPositionType> {
        let mut positions = vec![PlayerPositionType::Goalkeeper];
        positions.extend(OUTFIELD);
        positions
    }

    /// Seventeen-year-olds at the 0.47 of potential the database's
    /// seventeen-year-olds hold, developed for `seasons` seasons.
    fn from_seventeen(
        pa: u8,
        club: Club,
        role: Role,
        character: f32,
        positions: &[PlayerPositionType],
        seasons: i32,
    ) -> Self {
        let ca = (pa as f32 * 0.47).round() as u8;
        Self::from_age(17, pa, ca, club, role, character, positions, seasons)
    }

    fn from_age(
        age: u32,
        pa: u8,
        ca: u8,
        club: Club,
        role: Role,
        character: f32,
        positions: &[PlayerPositionType],
        seasons: i32,
    ) -> Self {
        let start = Self::start();
        let careers = positions
            .iter()
            .enumerate()
            .map(|(k, position)| {
                let id = 100 + k as u32 + (character as u32) * 10 + age * 1000;
                let player = Prospect::build(id, *position, start, age, pa, ca, character);
                Career::new(player, club, role, start).run_seasons(seasons)
            })
            .collect();
        Cohort { careers }
    }

    fn mean_ratio(&self, age: u8) -> f32 {
        self.careers
            .iter()
            .map(|c| c.mark_at(age).ratio())
            .sum::<f32>()
            / self.careers.len() as f32
    }
}

/// The shipped database's player records, as far as the reference tables
/// read them.
#[derive(serde::Deserialize)]
struct DatabaseRecord {
    birth_date: String,
    positions: Vec<DatabasePosition>,
    potential_ability: i32,
    current_ability: i32,
    #[serde(default)]
    attrs: Value,
}

#[derive(serde::Deserialize)]
struct DatabasePosition {
    code: String,
}

#[derive(serde::Deserialize)]
struct DatabaseFile {
    players: Vec<DatabaseRecord>,
}

impl DatabaseRecord {
    fn load() -> Vec<DatabaseRecord> {
        use std::io::Read;
        let path = concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../database/src/data/database.db"
        );
        let file = std::fs::File::open(path).expect("the shipped database");
        let mut json = String::new();
        flate2::read::GzDecoder::new(file)
            .read_to_string(&mut json)
            .expect("a gzipped database");
        serde_json::from_str::<DatabaseFile>(&json)
            .expect("database records")
            .players
    }

    fn age(&self) -> u8 {
        (2026 - self.birth_date[0..4].parse::<i32>().unwrap()) as u8
    }

    /// `db_curve.jq`'s `grp`.
    fn group(&self) -> usize {
        match self.positions[0].code.as_str() {
            "GK" => 0,
            "DC" | "DL" | "DR" | "WBL" | "WBR" => 1,
            "DM" | "MC" | "ML" | "MR" => 2,
            _ => 3,
        }
    }

    fn ratio(&self) -> f32 {
        self.current_ability as f32 / self.potential_ability as f32
    }
}

/// Every reference table is the shipped database's: one figure of each,
/// recomputed from the records the game loads.
#[test]
fn the_reference_tables_are_the_databases() {
    let records = DatabaseRecord::load();
    let median = |pick: &dyn Fn(&DatabaseRecord) -> bool| {
        let mut v: Vec<f32> = records
            .iter()
            .filter(|r| r.potential_ability >= 110 && pick(r))
            .map(|r| r.ratio())
            .collect();
        v.sort_by(|a, b| a.total_cmp(b));
        let near = v[((v.len() as f32 * 0.5).ceil() as usize) - 1];
        (near * 1000.0).round() / 1000.0
    };
    let representative = [
        PlayerPositionType::Goalkeeper,
        PlayerPositionType::DefenderCenter,
        PlayerPositionType::MidfielderCenter,
        PlayerPositionType::Striker,
    ];
    for (g, position) in representative.into_iter().enumerate() {
        let recomputed = median(&|r| r.group() == g && r.age() == 26);
        let (_, _, table, _, _) = RealWorld::group_at(position, 26);
        assert!(
            (recomputed - table).abs() < 1e-3,
            "group {g} at 26: the database says {recomputed:.3}, the table {table:.3}"
        );
    }
    let outfield = median(&|r| r.group() != 0 && r.age() == 24);
    let keepers = median(&|r| r.group() == 0 && r.age() == 24);
    let (_, _, outfield_table, _) = RealWorld::at(PlayerPositionType::Striker, 24);
    let (_, _, keeper_table, _) = RealWorld::at(PlayerPositionType::Goalkeeper, 24);
    assert!(
        (outfield - outfield_table).abs() < 1e-3,
        "outfield at 24: {outfield:.3}"
    );
    assert!(
        (keepers - keeper_table).abs() < 1e-3,
        "keepers at 24: {keepers:.3}"
    );

    for g in 0..4 {
        let pace: Vec<f32> = records
            .iter()
            .filter(|r| {
                (120..=165).contains(&r.potential_ability)
                    && r.group() == g
                    && (28..=30).contains(&r.age())
            })
            .filter_map(|r| r.attrs.pointer("/player/physical/pac")?.as_f64())
            .map(|pace| pace as f32)
            .collect();
        let recomputed = (pace.iter().sum::<f32>() / pace.len() as f32 * 10.0).round() / 10.0;
        let row = RealWorld::ATTRIBUTES_BY_AGE
            .iter()
            .find(|row| row.0 == g && row.1 == 28)
            .unwrap();
        assert!(
            (recomputed - row.5[0]).abs() < 0.05,
            "group {g} pace at 28-30: the database says {recomputed:.1}, the table {:.1}",
            row.5[0]
        );
    }
}

