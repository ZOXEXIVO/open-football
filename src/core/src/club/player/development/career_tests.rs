/// The maturation ceiling is the most a player of an age can hold. Read
/// as a share of ability it sits within a few hundredths of the real top
/// decile, so the database's best young players are not frozen above it
/// on day one.
#[test]
fn the_age_ceiling_holds_the_real_top_decile() {
    let start = Cohort::start();
    for pa in [120u8, 150, 180] {
        for position in Cohort::every_role() {
            let mut player = Prospect::build(1, position, start, 22, pa, 60, 12.0);
            Envelope::bank(&mut player, 1.0);
            // The database's players "of an age" turn it in 2026, so at the
            // world start they are on average a month into it.
            let envelope = |age: u8| Envelope::at(&player, age as f32 + 0.1);
            // Keepers mature latest: their ceiling trails the real top
            // decile by more, and reaches the real keeper's lower quartile
            // rather than his median. A keeper's career sits above it on
            // the outfield and physical attributes he carries past their
            // ceilings.
            let keeper = position == PlayerPositionType::Goalkeeper;
            let (ages, slack) = if keeper {
                ([22u8, 24, 27], 0.10)
            } else {
                ([21u8, 24, 27], 0.04)
            };
            for age in ages {
                let (_, p25, median, p90) = RealWorld::at(position, age);
                let floor = if keeper { p25 } else { median };
                let held = envelope(age);
                assert!(
                    held >= p90 - slack && held >= floor,
                    "{position:?} PA {pa} may hold {held:.3} at {age}; the real p90 is {p90:.3}"
                );
            }
            let teenager = envelope(17);
            assert!(
                teenager <= 0.78,
                "{position:?} PA {pa}: a seventeen-year-old may already hold {teenager:.3}"
            );
        }
    }
}

