/// How much football a player gets.
#[derive(Clone, Copy, Debug, PartialEq)]
enum Role {
    /// Starts every senior match.
    Starter,
    /// Starts every other senior match.
    Rotation,
    /// Comes on for the last 25 minutes of every senior match.
    Substitute,
    /// Starts every match for the club's youth side, whose league the game
    /// runs as friendlies.
    YouthRegular,
    /// Trains with the seniors and never plays.
    Unused,
    /// Out injured: no session, no match, no camp.
    Injured,
    /// Without a club: no session, no match, no camp, no coach.
    Free,
}

impl Role {
    /// Minutes on the `fixture`-th senior fixture date and whether they are
    /// a friendly's.
    fn appearance(self, fixture: u32) -> Option<(f32, bool)> {
        match self {
            Role::Starter => Some((90.0, false)),
            Role::Rotation => (fixture % 2 == 0).then_some((90.0, false)),
            Role::Substitute => Some((25.0, false)),
            Role::YouthRegular => Some((90.0, true)),
            Role::Unused | Role::Injured | Role::Free => None,
        }
    }
}

