/// A regular out for the whole season from `out_at`, against his healthy
/// twin; `(age, CA/PA out, CA/PA healthy)` from 20.
fn a_season_out(position: PlayerPositionType, out_at: u32) -> Vec<(u8, f32, f32)> {
    let run = |spells| {
        Scenario::run(
            Scenario::player(900 + position as u32, position, 17, 150, 0.47),
            spells,
            35,
        )
    };
    let healthy = run(GrowthTable::one(Club::AVERAGE, Role::Starter));
    let out = run(vec![
        Spell {
            from_age: 0,
            club: Club::AVERAGE,
            role: Role::Starter,
        },
        Spell {
            from_age: out_at,
            club: Club::AVERAGE,
            role: Role::Injured,
        },
        Spell {
            from_age: out_at + 1,
            club: Club::AVERAGE,
            role: Role::Starter,
        },
    ]);
    (20..=35u8)
        .map(|age| (age, Scenario::at(&out, age), Scenario::at(&healthy, age)))
        .collect()
}

